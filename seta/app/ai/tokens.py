"""Общее правило для всех текстов, которые пишет модель: числа — метками.

Правило одно на все сценарии, поэтому и живёт оно в одном месте. Разошлись бы
два описания — и в сводке цифры проверялись бы, а в отчёте нет; заметить такое
можно было бы только по жалобе на неверное число, то есть поздно.

**Модель не пишет чисел.** Она расставляет метки вида `{overdue}`, значения
подставляет код — из того же, что человек увидит следом. Совпадение получается
по построению, а не по обещанию.

**Ответ с цифрой отвергается целиком, а не чинится.** Ответ, в котором модель
нарушила одно правило, нечем отличить от ответа, в котором она нарушила два.
Починенный наполовину текст выглядит исправным и потому опаснее отброшенного:
взамен всегда есть чем ответить — тем, что система посчитала сама.

**Остаточный риск назван честно.** Правило ловит цифры, а не числа словами:
«три просрочки» от «в три раза» в трёх языках не отличить, а отвергать всё
подряд значит выключить функцию. Промпт просит не писать чисел словами;
гарантия даётся только про цифры.
"""
import re

TOKEN = re.compile(r"\{([a-z_0-9]{1,32})\}")
DIGIT = re.compile(r"\d")

from app.core.text import esc  # noqa: E402  (после регулярных выражений — читается сверху вниз)


def usable(
    raw: str,
    values: dict[str, str],
    *,
    min_lines: int,
    max_lines: int,
    max_chars: int,
) -> str | None:
    """Годен ли ответ модели. None — не годен, и уходит то, что посчитано.

    Границы задаёт вызывающий: вступлению к сводке хватает четырёх строк,
    недельному отчёту нужно больше. Правила при этом одни и те же.
    """
    text = (raw or "").strip()
    if not text:
        return None
    if DIGIT.search(text):
        # Цифру принесла модель — значит, это число, которое никто не считал.
        return None
    if any(token not in values for token in TOKEN.findall(text)):
        # Метка не из списка: либо выдумана, либо про то, чего сегодня нет.
        return None

    lines = [line.strip() for line in text.splitlines() if line.strip()]
    if not min_lines <= len(lines) <= max_lines:
        return None
    if sum(len(line) for line in lines) > max_chars:
        return None
    return "\n".join(lines)


def fill(text: str, values: dict[str, str]) -> str:
    """Подставляет значения. Вызывается только после `usable`.

    Полнота списка меток — её забота: здесь неизвестная метка означает
    сломанный порядок вызовов, и падать честнее, чем молча подставить пустоту.

    Экранирование раньше подстановки — намеренно: текст пишет модель,
    а название отдела человек, и в сообщение с разметкой оба попадают
    экранированными. Метки при этом не страдают: фигурные скобки для HTML —
    обычные знаки.
    """
    return TOKEN.sub(lambda found: esc(values[found.group(1)]), esc(text))


def numbers(text: str) -> set[str]:
    """Все числа, встречающиеся в тексте. Для сверки с посчитанным."""
    return set(re.findall(r"\d+", text or ""))
