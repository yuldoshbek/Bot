"""Промпты — в одном месте и с версиями.

**Почему отдельным модулем.** Промпт — не строка интерфейса и не сообщение
человеку: его читает модель. Держать его рядом с текстами кнопок значит
однажды перевести его на узбекский вместе с ними. Держать по одному в каждом
сценарии — значит не иметь возможности прочесть их все подряд, а именно так
их и приходится читать, когда разбираешься, почему ответы поехали.

**Почему по-русски.** Промпт правит владелец системы, а не только модель.
Промпт, который некому вычитать, — чёрный ящик внутри собственного кода.

**Почему версия рядом.** Версия уходит в журнал вызовов. Изменили формулировку,
не тронув версию, — и объяснить, почему вчера разбор был другим, уже нечем.
Правило простое: меняется текст — меняется версия.
"""
from dataclasses import dataclass


@dataclass(frozen=True, slots=True)
class Prompt:
    """Указание модели и версия этого указания."""

    version: str
    system: str


