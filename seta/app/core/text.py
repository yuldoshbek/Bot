"""Подготовка пользовательского текста к отправке в Telegram.

Сообщения отправляются в режиме HTML, и Telegram разбирает разметку строго:
неизвестный тег — и сообщение не доходит ни до кого. Название поручения
«Проверить <новый> регламент» или фамилия с угловой скобкой ломают карточку
целиком, а не только себя.

Поэтому любой текст, пришедший от человека, перед вставкой в сообщение
пропускается через esc(). Собственная разметка (<b>, <code>) пишется в коде
и экранированию не подлежит.

В базе текст хранится как есть: экранирование — свойство показа,
а не свойство данных. Иначе выгрузки и поиск получат «&lt;» вместо «<».
"""
import html


def esc(value: object) -> str:
    """Экранирует текст от человека для вставки в HTML-сообщение."""
    if value is None:
        return ""
    return html.escape(str(value), quote=False)


def cut(value: str, limit: int) -> str:
    """Обрезает длинный текст, чтобы сообщение уместилось в лимит Telegram."""
    value = value.strip()
    if len(value) <= limit:
        return value
    return value[: limit - 1].rstrip() + "…"
