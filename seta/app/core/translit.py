"""Узбекская латиница → кириллица.

Две письменности узбекского связаны правилом, а не словарём: каждой букве
латиницы отвечает буква кириллицы, и обратно. Поэтому вторая письменность
не переводится вручную, а выводится из первой.

**Почему так, а не два словаря.** Полторы тысячи строк, набранных дважды,
расходятся на первой же правке: кто-то поправит формулировку в одной
письменности и забудет о второй. Пользователь увидит в одном месте одно,
в другом другое — и перестанет верить обоим. Один источник и правило перевода
такого расхождения не допускают в принципе.

**Где правило не работает — там исключение, а не отказ от правила.**
Заимствования и имена собственные иногда пишутся не по общей схеме; для них
есть таблица исключений в `app/i18n/uz_cyrl.py`, и она короткая. Правило
покрывает подавляющую часть текста, исключения — остаток.

Порядок замен важен: `oʻ` разбирается раньше, чем `o`, иначе `yoʻl` («путь»)
превратился бы в «ёл» вместо «йўл».
"""
import re

# Апостроф в узбекской латинице пишут по-разному: типографский ʻ, машинный ',
# правый ’, обратный `. Для читателя это один знак, и разбор обязан принимать все.
APOSTROPHES = "ʻ'’‘`ʼ"
_APO = f"[{re.escape(APOSTROPHES)}]"

# Диграфы разбираются первыми: буква, склеенная из двух знаков, не должна
# распасться на два независимых перевода.
DIGRAPHS: list[tuple[str, str]] = [
    ("o" + "ʻ", "ў"),      # oʻ
    ("g" + "ʻ", "ғ"),      # gʻ
    ("sh", "ш"),
    ("ch", "ч"),
    ("ts", "ц"),
    ("yo", "ё"),
    ("yu", "ю"),
    ("ya", "я"),
    ("ye", "е"),
]

# Буквы, которые связывают апостроф крепче любого другого диграфа. Без этого
# «yoʻl» («путь») разбирался бы как «yo» + апостроф и давал «ёʻл» вместо «йўл»:
# «y» тут отдельная буква, а «oʻ» — цельная.
TIGHT = ("oʻ", "gʻ")

# Латиница, которая не является узбекским словом, переводу не подлежит:
# «Excel» в кириллическом тексте так и пишется «Excel», а не «Эхcел».
# Признак не список названий, а орфография: буквы «c» (вне «ch») и «w»
# в узбекской латинице не встречаются вовсе, а слово целиком прописными —
# это сокращение вроде PDF, а не слово.
FOREIGN = re.compile(r"c(?!h)|w", re.IGNORECASE)
LATIN_RUN = re.compile(r"[A-Za-z]+")


def _is_foreign(word: str) -> bool:
    """Слово написано латиницей, но узбекским не является.

    Единственный случай, который правило прочтёт неверно, — узбекское слово,
    набранное целиком прописными. Такого в словаре нет и быть не должно:
    интерфейс не кричит. Если понадобится — это строка для таблицы исключений.
    """
    if FOREIGN.search(word):
        return True
    return len(word) > 1 and word.isupper()


LETTERS: dict[str, str] = {
    "a": "а", "b": "б", "d": "д", "e": "е", "f": "ф", "g": "г", "h": "ҳ",
    "i": "и", "j": "ж", "k": "к", "l": "л", "m": "м", "n": "н", "o": "о",
    "p": "п", "q": "қ", "r": "р", "s": "с", "t": "т", "u": "у", "v": "в",
    "x": "х", "y": "й", "z": "з",
    # Твёрдый знак: в латинице это тот самый апостроф, но уже как буква.
    "ʼ": "ъ",
}


def _normalize(text: str) -> str:
    """Сводит все начертания апострофа к двум знакам: ʻ у букв, ʼ у твёрдого.

    Различить их можно по соседям: после o и g апостроф образует букву,
    в остальных местах он сам буква.
    """
    # Порядок обратный ожидаемому: сначала всё сводится к одному знаку, потом
    # из него выделяется буквенный. Наоборот не работает — вторая замена
    # съедала бы результат первой, и «Oʻzbekiston» превращался в «Оъзбекистон».
    text = re.sub(_APO, "ʼ", text)
    return re.sub(r"([oOgG])ʼ", r"\1ʻ", text)


def _match_case(source: str, target: str) -> str:
    """Переносит регистр исходного куска на перевод."""
    if source.isupper() and len(source) > 1:
        return target.upper()
    if source[:1].isupper():
        return target[:1].upper() + target[1:]
    return target


def to_cyrillic(text: str) -> str:
    """Переводит узбекскую латиницу в кириллицу.

    Небуквенное — цифры, знаки, разметка сообщения, подстановки вида {name} —
    проходит насквозь: перевод письменности не должен трогать ни HTML-теги,
    ни имена подстановок, иначе сообщение развалится ещё до отправки.
    """
    if not text:
        return text
    text = _normalize(text)

    result: list[str] = []
    index = 0
    length = len(text)
    # Слово только начинается, если перед нами не буква: от этого зависит,
    # станет ли «e» буквой «э» или «е».
    at_word_start = True

    while index < length:
        char = text[index]

        # Разметка сообщения и подстановки пропускаются целиком: внутри них
        # латиница — это код, а не текст.
        if char == "<":
            close = text.find(">", index)
            if close != -1:
                result.append(text[index:close + 1])
                index = close + 1
                continue
        if char == "{":
            close = text.find("}", index)
            if close != -1:
                result.append(text[index:close + 1])
                index = close + 1
                continue

        # Иностранное слово проходит целиком и без изменений. Проверяется
        # оно один раз, на первой букве: разбирать «Excel» по буквам поздно —
        # к «c» уже потеряно знание о том, частью какого слова она была.
        if at_word_start and char.isascii() and char.isalpha():
            run = LATIN_RUN.match(text, index)
            if run is not None and _is_foreign(run.group()):
                result.append(run.group())
                index = run.end()
                at_word_start = False
                continue

        # Если со следующей буквы начинается «oʻ» или «gʻ», текущую нельзя
        # склеивать с ней в диграф: она сама по себе.
        binds_next = text[index + 1:index + 3].lower() in TIGHT

        lowered = text[index:index + 2].lower()
        pair = next((cyr for lat, cyr in DIGRAPHS if lat == lowered), None)
        if pair is not None and not binds_next:
            result.append(_match_case(text[index:index + 2], pair))
            index += 2
            at_word_start = False
            continue

        single = char.lower()
        if single == "e" and at_word_start:
            result.append(_match_case(char, "э"))
            index += 1
            at_word_start = False
            continue

        mapped = LETTERS.get(single)
        if mapped is not None:
            result.append(_match_case(char, mapped))
            index += 1
            at_word_start = False
            continue

        result.append(char)
        at_word_start = not char.isalpha()
        index += 1

    return "".join(result)
