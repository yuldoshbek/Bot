"""Кому из браузера разрешено обращаться к API.

**Это разрешение, а не рубеж.** Рубеж один и стоит выше — подпись `initData`
в `app/api/initdata.py`. CORS ничего не охраняет: правило исполняет браузер,
а `curl` его не спрашивает вовсе. Задача этого модуля обратная — **позволить**
приложению, которое лежит на другом адресе, дозвониться до API.

Отсюда всё остальное.

**Адрес не задан — правила нет вовсе.** Не звёздочка «на всякий случай»,
а отсутствие слоя: разрешать нечего, пока приложения нет. Звёздочка,
поставленная однажды «пока не настроим», остаётся навсегда.

**Источник точный, а не по маске.** `*.vercel.app` — это не наше приложение,
а весь хостинг: любое чужое приложение на том же домене попадает под маску.

**Предварительные сборки до боевого API не достучатся.** Vercel выдаёт каждому
коммиту свой адрес, и в списке разрешённых его нет. Так и должно быть: черновик
не приложение, и проверять правки на живых данных кабинета — не то, чего хочется
случайно.

**Список заголовков перечислен.** `X-Telegram-Init-Data` — не из стандартных,
и без явного разрешения браузер вырежет его на предварительном запросе, а API
ответит «нет initData» на совершенно правильный вызов.
"""
import logging

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app.core.config import settings

log = logging.getLogger("seta.api")

# Заголовок, в котором приходит подписанная строка. Он же — единственная
# причина, по которой список заголовков вообще приходится перечислять.
INIT_DATA_HEADER = "X-Telegram-Init-Data"

# Приложение только читает. Разрешать ему методы записи незачем: маршрутов
# записи в API нет, и появиться они должны осознанно, а не потому, что метод
# был разрешён заранее.
METHODS = ("GET", "OPTIONS")


def origins() -> list[str]:
    """Кому разрешено. Пустой список означает «никому», и это нормально."""
    origin = settings.miniapp_origin
    if origin:
        return [origin]
    if settings.miniapp_url.strip():
        # Адрес задан, но разобрать его не вышло — обычно забыта схема.
        # Молчать здесь нельзя: приложение не получит ни одного ответа,
        # а в журнале не будет ни строчки о причине.
        log.warning(
            "MINIAPP_URL задан, но не похож на адрес: %r. "
            "Ожидается вид https://приложение.example — со схемой.",
            settings.miniapp_url,
        )
    return []


def apply(app: FastAPI) -> list[str]:
    """Ставит правило на приложение. Возвращает то, что разрешил.

    Вызывается и боевым приложением, и проверкой — одним и тем же кодом:
    правило, проверяемое отдельной копией, проверяет копию.
    """
    allowed = origins()
    if not allowed:
        return []
    app.add_middleware(
        CORSMiddleware,
        allow_origins=allowed,
        allow_methods=list(METHODS),
        allow_headers=[INIT_DATA_HEADER, "Content-Type"],
        # Печенья не используются: приложение представляется подписью
        # на каждом запросе. Разрешать их означало бы завести второй способ
        # узнать человека — и однажды поверить именно ему.
        allow_credentials=False,
        max_age=600,
    )
    log.info("приложению разрешено обращаться к API: %s", ", ".join(allowed))
    return allowed
